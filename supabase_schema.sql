-- Run this entire script in Supabase: SQL Editor > New query > Run.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password_hash text not null,
  role text not null check (role in ('admin','staff'))
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  quantity integer not null check (quantity >= 0),
  min_stock integer not null check (min_stock >= 0),
  price numeric(12,2) not null check (price >= 0),
  suppliers text not null default '',
  created_at text not null
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  kind text not null check (kind in ('IN','OUT')),
  quantity integer not null check (quantity > 0),
  price numeric(12,2) not null,
  note text,
  username text not null,
  created_at text not null
);

-- Existing project migration: add supplier list to each product. Safe to run more than once.
alter table public.products add column if not exists suppliers text not null default '';

-- Atomic stock update + transaction logging prevents partial updates.
create or replace function public.record_stock(
  p_product_id bigint,
  p_kind text,
  p_quantity integer,
  p_note text,
  p_username text
) returns void
language plpgsql
security invoker
as $$
declare
  p public.products%rowtype;
  new_qty integer;
begin
  if p_kind not in ('IN','OUT') or p_quantity <= 0 then
    raise exception 'Invalid stock movement.';
  end if;
  select * into p from public.products where id = p_product_id for update;
  if not found then raise exception 'Product not found.'; end if;
  if p_kind = 'OUT' and p_quantity > p.quantity then
    raise exception 'Insufficient stock. Only % units available.', p.quantity;
  end if;
  if p_kind = 'IN' then new_qty := p.quantity + p_quantity;
  else new_qty := p.quantity - p_quantity; end if;
  update public.products set quantity = new_qty where id = p_product_id;
  insert into public.transactions(product_id, product_name, kind, quantity, price, note, username, created_at)
  values(p.id, p.name, p_kind, p_quantity, p.price, coalesce(p_note,''), p_username, to_char(now(), 'YYYY-MM-DD HH24:MI:SS'));
end;
$$;

